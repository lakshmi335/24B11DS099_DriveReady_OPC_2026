# (2) the prompt template: {business} and {question} are blanks
from langchain_core.prompts import ChatPromptTemplate, MessagesPlaceholder
from langchain_core.output_parsers import StrOutputParser

prompt_basic = ChatPromptTemplate.from_messages([
    ("system", "You are the assistant for {business}. Answer in under 30 words."),
    ("human",  "{question}"),
])

# (3) the chain: fill blanks -> ask model -> keep just the text
chain_basic = prompt_basic | llm | StrOutputParser()

print(chain_basic.invoke({"business": "Sweet Crumbs Home Bakery", "question": "Do you make eggless cakes?"}))
# same template, new assistant:
print(chain_basic.invoke({"business": "Bright Minds Tuition Centre", "question": "Do you teach Maths?"}))

#build – Sweet Crumbs assistant: template + memory + chain
SYSTEM = """ROLE:   You are the friendly assistant for Sweet Crumbs Home Bakery.
FACTS:  Plum cake Rs 500. Chocolate cake Rs 650. Cupcake Rs 80 each.
        Orders need 24 hours' notice. All cakes have eggless versions.
RULES:  Never promise a delivery time or place. If it isn't in FACTS,
        say "I'll check with the owner." Work out totals carefully.
FORMAT: Under 50 words, friendly, English or Telugu matching the customer."""
# NOTE: no { } inside SYSTEM - curly braces are "blanks" in a template (or double them: {{ }})

prompt = ChatPromptTemplate.from_messages([
    ("system", SYSTEM),
    MessagesPlaceholder("history"),          # the chat so far goes here
    ("human", "{question}"),
])
chain = prompt | llm | StrOutputParser()

history = []
def ask(question: str) -> str:
    answer = chain.invoke({"history": history, "question": question})
    history.extend([("human", question), ("ai", answer)])
    return answer

print(ask("Hi, I'm Ravi. Do you make eggless cakes?"))
print(ask("What's my name?"))

#Test it
