import csv

def run_tests(path: str = "tests.csv", answer_fn=None) -> float:
    """Run every row of the CSV and return the pass rate (0 to 1)."""
    if answer_fn is None:
        answer_fn = lambda q: chain.invoke({"history": [], "question": q})
    with open(path, encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    passed = 0
    for row in rows:
        answer = answer_fn(row["question"])
        ok = row["must_include"].lower() in answer.lower()
        passed += ok
        print("PASS" if ok else "FAIL", "|", row["question"], "->", answer[:70].replace("\n", " "))
    rate = passed / len(rows)
    print(f"\n{passed}/{len(rows)} passed ({rate:.0%})")
    return rate

