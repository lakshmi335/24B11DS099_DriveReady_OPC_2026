MY_TEMPLATE = """ROLE:   You are the friendly assistant for {business}.
FACTS:  {facts}
RULES:  Never promise a seat or a discount. If it isn't in FACTS, say "I'll check with the owner."
FORMAT: Under 50 words, friendly."""

my_prompt = ChatPromptTemplate.from_messages([
    ("system", MY_TEMPLATE),
    ("human", "{question}"),
])
my_chain = my_prompt | llm | StrOutputParser()

MY_INPUT = {
    "business": "Bright Minds Tuition Centre",
    "facts": ("Classes 6 to 10 in Maths, Science and English. Fee Rs 1500 per subject per month, "
              "Rs 3600 for all three. Batches Mon-Fri 5-7 PM and Sat 9 AM-12 PM. "
              "Maximum 15 students per batch. Free demo class on request."),
}

def my_ask(question: str) -> str:
    return my_chain.invoke({**MY_INPUT, "question": question})

print(my_ask("What is the fee for all three subjects?"))
print(my_ask("Do you have a Sunday batch?"))

