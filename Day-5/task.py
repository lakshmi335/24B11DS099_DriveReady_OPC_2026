def run_tests(path, answer_fn, only_last=None):
    """Run every row; PASS if the answer contains any of the words in must_include (split by |)."""
    rows = list(csv.DictReader(open(path, encoding="utf-8")))
    if only_last:
        rows = rows[-only_last:]
    passed = 0
    for row in rows:
        answer = answer_fn(row["question"])
        ok = any(w.strip().lower() in answer.lower() for w in row["must_include"].split("|"))
        passed += ok
        print("PASS" if ok else "FAIL", "|", row["question"], "->", answer[:80].replace("\n", " "))
    rate = passed / len(rows)
    print(f"\n{passed}/{len(rows)} passed ({rate:.0%})")
    return rate

