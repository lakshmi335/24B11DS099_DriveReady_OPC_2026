""" Chunking: one idea per chunk, a little overlap"""

def chunk(text: str, size: int = 300, overlap: int = 50) -> list[str]:
    """Split text into pieces of about `size` characters that overlap by `overlap`."""
    assert overlap < size, "overlap must be smaller than size"
    pieces, start = [], 0
    while start < len(text):
        pieces.append(text[start:start + size])
        start += size - overlap
    return pieces

