# ask for JSON, then json.loads inside try/except
ORDER_SYSTEM = """Extract the order from the customer's message.
Return ONLY JSON, no other text, with these keys:
name (text), item (text), qty (number), date (text), eggless (true/false)."""

def extract_order(message: str):
    reply = ask([{"role":"system","content":ORDER_SYSTEM}, {"role":"user","content":message}], temperature=0)
    # models sometimes wrap JSON in ```json fences -> strip them
    cleaned = re.sub(r"^```(?:json)?|```$", "", reply.strip(), flags=re.MULTILINE).strip()
    try:
        return json.loads(cleaned)
    except json.JSONDecodeError:
        print("Could not parse JSON. Raw reply was:\n", reply)
        return None

