from google.colab import userdata
from openai import OpenAI

client = OpenAI(
    api_key=userdata.get("GROQ_API_KEY"),
    base_url="https://api.groq.com/openai/v1",
)
MODEL = "openai/gpt-oss-20b"   # if you get 404, run: [m.id for m in client.models.list().data]

def ask(messages, temperature=0.7):
    r = client.chat.completions.create(model=MODEL, messages=messages, temperature=temperature)
    return r.choices[0].message.content, r.usage

# First API vall
resp = client.chat.completions.create(
    model=MODEL,
    messages=[
        {"role": "system", "content": "You are a funny joker"},
        {"role": "user",   "content": "tell me a joke"},
    ],
)
print(resp.choices[0].message.content)

#Sweet Crumbs bakery bot(facts+low temperature)
SYSTEM = """ROLE:   You are the assistant for Sweet Crumbs Home Bakery.
FACTS:  We bake to order. Orders need 24 hours' notice. All cakes have eggless versions.
        Plum cake Rs 500. Chocolate cake Rs 650. Cupcake Rs 80.
RULES:  Never promise a delivery time. If the answer isn't in FACTS, say "I'll check with the owner."
FORMAT: Under 50 words, friendly, English or Telugu matching the customer."""

resp = client.chat.completions.create(
    model=MODEL,
    temperature=0.2,
    messages=[{"role": "system", "content": SYSTEM},
              {"role": "user",   "content": "Can I get an eggless cake today evening?"}],
)
print(resp.choices[0].message.content)
print(resp.usage)

# Temperature:0.2 vs 1.2
q = [{"role": "user", "content": "Write a tagline for Sweet Crumbs Home Bakery"}]
for t in (0.2, 1.2):
    print(f"\n--- temperature {t} ---")
    for i in range(3):
        text, _ = ask(q, temperature=t)
        print(i+1, text.strip())

# Hallucination: remove facts and ask about delivery
no_facts = "You are the assistant for Sweet Crumbs Home Bakery. Answer customer questions."
q = {"role": "user", "content": "Do you deliver to Kakinada? What are the charges?"}

print("WITHOUT facts:\n", ask([{"role":"system","content":no_facts}, q])[0])
print("\nWITH facts + 'not found' rule:\n", ask([{"role":"system","content":SYSTEM}, q], temperature=0.2)[0])

#separate calls vs resending history
# Two separate calls -> model forgets
print(ask([{"role":"user","content":"My name is Dhanu"}])[0])
print("\nSeparate call:", ask([{"role":"user","content":"What is my name?"}])[0])

# One messages list with history -> model 'remembers'
history = [
    {"role":"user","content":"My name is Dhanu"},
    {"role":"assistant","content":"Nice to meet you, Dhanu!"},
    {"role":"user","content":"What is my name?"},
]
print("\nWith history:", ask(history)[0])

#tokens: English vs Telugu
en = "Can I get an eggless cake today evening?"
te = "ఈ రోజు సాయంత్రం ఎగ్‌లెస్ కేక్ దొరుకుతుందా?"

for label, text in (("English", en), ("Telugu", te)):
    _, usage = ask([{"role":"system","content":SYSTEM},{"role":"user","content":text}], temperature=0.2)
    print(f"{label}: prompt_tokens={usage.prompt_tokens}, completion_tokens={usage.completion_tokens}")

# system prompt for a sample business: Bright Minds Tuition Centre
MY_SYSTEM = """ROLE:   You are the assistant for Bright Minds Tuition Centre.
FACTS:  1) We teach Maths, Science and English for classes 6 to 10.
        2) Batches run Monday to Friday, 5 PM to 7 PM, and Saturday 9 AM to 12 PM.
        3) Monthly fee: Rs 1,500 per subject, or Rs 3,600 for all three subjects.
        4) Each batch has a maximum of 15 students.
        5) A free demo class is available on request.
RULES:  1) Never promise a seat; seats depend on the batch being free.
        2) If the answer isn't in FACTS, say "I'll check with the owner."
        3) Never give discounts or change fees; only quote the fees in FACTS.
FORMAT: Under 50 words, friendly, English or Telugu matching the customer."""

questions = [
    "What is the fee for class 8 Maths?",
    "Do you give a free demo class?",
    "Do you have a Sunday batch for Physics?",   # not in FACTS -> should say "I'll check with the owner"
]

for qu in questions:
    ans, _ = ask(
        [{"role": "system", "content": MY_SYSTEM},
         {"role": "user", "content": qu}],
        temperature=0.2,
    )
    print("Q:", qu, "\nA:", ans, "\n")

history = [{"role": "system", "content": SYSTEM}]
while True:
    user = input("You: ")
    if user.strip().lower() == "quit":
        break
    history.append({"role": "user", "content": user})
    r = client.chat.completions.create(model=MODEL, messages=history, temperature=0.2)
    reply = r.choices[0].message.content
    history.append({"role": "assistant", "content": reply})
    print("Bot:", reply, f"  [prompt tokens: {r.usage.prompt_tokens}]")