# count tool calls and model calls
from langchain_core.messages import AIMessage, ToolMessage

def count_calls(result):
    msgs = result["messages"]
    model_calls = sum(isinstance(m, AIMessage) for m in msgs)    # every AI message = one model call
    tool_calls  = sum(isinstance(m, ToolMessage) for m in msgs)  # every tool result = one tool call
    return model_calls, tool_calls

for q in ["Hello!", "Fee for Maths for 3 months?", "Fee for English for 2 months and is there a seat in Maths?"]:
    r = my_chat(q)
    if r:
        mc, tc = count_calls(r)
        print(f"{q!r:70} -> model calls: {mc}, tool calls: {tc}")

