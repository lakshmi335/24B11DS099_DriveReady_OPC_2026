FEES = {"maths": 1500, "science": 1500, "english": 1500}          # subject -> Rs per month
SEATS = {"maths": 4, "science": 0, "english": 9}                  # subject -> free seats

@tool
def get_fee(subject: str, months: int = 1) -> str:
    """Get the total tuition fee in rupees for a subject for a number of months.
    Args:
        subject: "maths", "science" or "english"
        months: how many months the parent wants to pay for
    """
    fee = FEES.get(subject.lower().strip())
    if fee is None:
        return f"'{subject}' is not offered. We teach: {', '.join(FEES)}."
    return f"{subject}, {months} month(s) = Rs {fee * months}"

@tool
def seats_available(subject: str) -> str:
    """Check how many free seats are left in a subject's batch, e.g. "maths"."""
    seats = SEATS.get(subject.lower().strip())
    if seats is None:
        return f"'{subject}' is not offered. We teach: {', '.join(SEATS)}."
    return f"{seats} seat(s) free in {subject}." if seats else f"{subject} batch is full."

